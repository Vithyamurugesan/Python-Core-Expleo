str1 = '''I'm a "Geek"'''

print("Initial String with Triple Quotes:")
print(str1)

print("\nEscaping Single Quote:")
print('I\'m a "Geek"')

print("\nEscaping Double Quotes:")
print("I'm a \"Geek\"")

print("\nEscaping Backslashes:")
print("C:\\Python\\Geeks\\")

print("\nTab:")
print("Hi\tGeeks")

print("\nNew Line:")
print("Python\nGeeks")